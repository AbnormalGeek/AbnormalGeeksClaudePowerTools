#!/usr/bin/env bash
# gen-persona-skills-test.sh — exercises tools/gen-persona-skills.sh against
# a throwaway fixture tree (never the real repo) via the GEN_PERSONA_ROOT
# override (repo mode) and --local/--out/--shared-root (local mode), and
# asserts:
#   1. happy path: 2 manifests -> 2 skills, exact expected SKILL.md content,
#      including the pinned overlay-aware for-loop loader body
#   2. a missing slice fails validation: nonzero exit, no partial writes
#   3. idempotence: a second run makes no changes; --check exits 0
#   4. a modified manifest makes --check exit 1
#   5. a stale AUTO-GENERATED skill (no manifest) is removed; a hand-made
#      persona-* skill WITHOUT the marker is preserved untouched
#   6. no manifests at all -> exit 0, graceful no-op
#   7. --local happy path: mixed plain/shared: slices, exact expected content
#   8. --local missing --out / --shared-root -> exit 2, names the flag
#   9. --local plain slice missing -> error; shared: slice missing in the
#      shared root -> error naming the shared root
#  10. --local collision: an existing non-local-marked skill at the target
#      name is never overwritten (error, not silent overwrite)
#  11. --local stale cleanup only ever considers local-marked skills — a
#      shared-generated (or hand-written) persona-* skill sharing the output
#      dir is never deleted even when no local manifest names it
#  12. --local --check works (up to date / would update)
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GEN_SRC="${SCRIPT_DIR}/../gen-persona-skills.sh"

pass=0
fail=0

ok()  { pass=$((pass + 1)); printf 'PASS: %s\n' "$1"; }
bad() { fail=$((fail + 1)); printf 'FAIL: %s\n' "$1"; }

assert_eq() {
  local desc="$1" expected="$2" actual="$3"
  if [[ "$expected" == "$actual" ]]; then
    ok "$desc"
  else
    bad "$desc (expected [$expected] got [$actual])"
  fi
}

assert_contains() {
  local desc="$1" haystack="$2" needle="$3"
  if [[ "$haystack" == *"$needle"* ]]; then
    ok "$desc"
  else
    bad "$desc (expected to find [$needle])"
  fi
}

assert_not_contains() {
  local desc="$1" haystack="$2" needle="$3"
  if [[ "$haystack" != *"$needle"* ]]; then
    ok "$desc"
  else
    bad "$desc (did not expect to find [$needle])"
  fi
}

# Isolate every scenario under a throwaway fixture tree that mimics
# claude-config/context + claude-config/skills — this must never touch the
# real AbnormalGeeksClaudePowerTools working tree.
TMP_ROOT="$(mktemp -d)"
trap 'rm -rf "$TMP_ROOT"' EXIT

CONTEXT_DIR="$TMP_ROOT/claude-config/context"
SKILLS_DIR="$TMP_ROOT/claude-config/skills"
PERSONAS_DIR="$CONTEXT_DIR/personas"
LOCAL_DIR="$TMP_ROOT/context-local"
OUT_DIR="$TMP_ROOT/local-skills-out"

# init_fixture — reset the throwaway tree to empty claude-config/{context,skills}
# plus an empty --local library and --out dir.
init_fixture() {
  rm -rf "$TMP_ROOT"
  mkdir -p "$CONTEXT_DIR/skills" "$SKILLS_DIR" "$LOCAL_DIR" "$OUT_DIR"
}

# write_slice <rel-path-under-context-skills> <content-line>
write_slice() {
  local rel="$1" content="$2"
  mkdir -p "$CONTEXT_DIR/skills/$(dirname "$rel")"
  printf '%s\n' "$content" > "$CONTEXT_DIR/skills/$rel"
}

# write_manifest <group> <persona> <description> <slice1> [slice2 ...]
write_manifest() {
  local group="$1" persona="$2" description="$3"
  shift 3
  mkdir -p "$PERSONAS_DIR/$group"
  {
    echo "---"
    echo "persona: $persona"
    echo "group: $group"
    echo "description: $description"
    echo "slices:"
    local s
    for s in "$@"; do
      echo "  - $s"
    done
    echo "---"
    echo "# Persona: $group/$persona"
    echo "Some prose that the generator must ignore."
    for s in "$@"; do
      echo "@../../$s"
    done
  } > "$PERSONAS_DIR/$group/$persona.md"
}

# expected_skill_content <group> <persona> <description> <slice1> [slice2 ...]
# — mirrors the generator's exact repo-mode output shape (single
# resolve-slices.sh helper call as the loader body), used to assert
# byte-for-byte.
expected_skill_content() {
  local group="$1" persona="$2" description="$3"
  shift 3
  local slices="$*"
  cat <<EOF
---
name: persona-${group}-${persona}
description: Persona loader — ${group}/${persona}: ${description} (AUTO-GENERATED by tools/gen-persona-skills.sh — edit the manifest/slices and regenerate; do not hand-edit)
---
# Persona: ${group}/${persona} (live from ~/.claude/context/, local overlay wins)

!\`bash ~/.claude/context/resolve-slices.sh ${slices}\`
EOF
}

# write_local_slice <rel-path-under-context-local-skills> <content-line>
write_local_slice() {
  local rel="$1" content="$2"
  mkdir -p "$LOCAL_DIR/skills/$(dirname "$rel")"
  printf '%s\n' "$content" > "$LOCAL_DIR/skills/$rel"
}

# write_local_manifest <group> <persona> <description> <slice1> [slice2 ...]
# — slice entries may be plain ("skills/...") or "shared:skills/..." to
# reference the shared library.
write_local_manifest() {
  local group="$1" persona="$2" description="$3"
  shift 3
  mkdir -p "$LOCAL_DIR/personas/$group"
  {
    echo "---"
    echo "persona: $persona"
    echo "group: $group"
    echo "description: $description"
    echo "slices:"
    local s
    for s in "$@"; do
      echo "  - $s"
    done
    echo "---"
    echo "# Persona: $group/$persona"
    echo "Some prose that the generator must ignore."
  } > "$LOCAL_DIR/personas/$group/$persona.md"
}

# expected_local_skill_content <group> <persona> <description> <slice1> [slice2 ...]
# — mirrors the generator's exact --local-mode output shape (single
# resolve-slices.sh helper call, same as repo mode, with any "shared:"
# prefix stripped from each slice path before it's passed as an argument).
expected_local_skill_content() {
  local group="$1" persona="$2" description="$3"
  shift 3
  local s stripped_slices=()
  for s in "$@"; do
    stripped_slices+=("${s#shared:}")
  done
  local slices="${stripped_slices[*]}"
  cat <<EOF
---
name: persona-${group}-${persona}
description: Persona loader — ${group}/${persona}: ${description} (AUTO-GENERATED (local) by tools/gen-persona-skills.sh --local — edit the manifest/slices and regenerate; do not hand-edit)
---
# Persona: ${group}/${persona} (local library; shared: slices resolve via the shared library overlay)

!\`bash ~/.claude/context/resolve-slices.sh ${slices}\`
EOF
}

run_gen() {
  # run_gen [--check]  -> sets OUT, CODE (repo mode, via GEN_PERSONA_ROOT)
  OUT="$(GEN_PERSONA_ROOT="$TMP_ROOT" "$GEN_SRC" "$@" 2>&1)"
  CODE=$?
}

run_gen_local() {
  # run_gen_local [--check]  -> sets OUT, CODE (--local mode against the
  # fixture's context-local dir / local-skills-out dir / shared CONTEXT_DIR)
  OUT="$(GEN_PERSONA_ROOT="$TMP_ROOT" "$GEN_SRC" --local "$LOCAL_DIR" --out "$OUT_DIR" --shared-root "$CONTEXT_DIR" "$@" 2>&1)"
  CODE=$?
}

# ---------------------------------------------------------------------------
# Test 1: happy path — 2 manifests -> 2 skills, exact expected content
# ---------------------------------------------------------------------------
init_fixture
write_slice "testing/core.md" "# core testing doctrine"
write_slice "testing/props.md" "# property testing doctrine"
write_slice "review/checklist.md" "# review checklist"
write_manifest "dev" "backend" "Backend engineer doctrine slice" \
  "skills/testing/core.md" "skills/testing/props.md"
write_manifest "review" "lead" "Review lead doctrine slice" \
  "skills/review/checklist.md"

run_gen
assert_eq "happy path: exit 0" "0" "$CODE"
assert_contains "happy path: reports created dev/backend" "$OUT" "created: persona-dev-backend"
assert_contains "happy path: reports created review/lead" "$OUT" "created: persona-review-lead"

actual1="$(cat "$SKILLS_DIR/persona-dev-backend/SKILL.md")"
expected1="$(expected_skill_content "dev" "backend" "Backend engineer doctrine slice" \
  "skills/testing/core.md" "skills/testing/props.md")"
assert_eq "happy path: dev/backend content exact" "$expected1" "$actual1"

actual2="$(cat "$SKILLS_DIR/persona-review-lead/SKILL.md")"
expected2="$(expected_skill_content "review" "lead" "Review lead doctrine slice" \
  "skills/review/checklist.md")"
assert_eq "happy path: review/lead content exact" "$expected2" "$actual2"

# Overlay body correctness — the loader body must be the single, pinned
# resolve-slices.sh helper call, byte for byte (independent of the local
# helper above duplicating the same shape).
assert_contains "overlay body: exact pinned resolve-slices.sh call" "$actual1" \
  '!`bash ~/.claude/context/resolve-slices.sh skills/testing/core.md skills/testing/props.md`'
assert_contains "overlay body: header names local overlay" "$actual1" \
  "(live from ~/.claude/context/, local overlay wins)"

# ---------------------------------------------------------------------------
# Test 2: missing slice -> nonzero exit, no partial writes (neither the
# invalid manifest's skill nor an otherwise-valid sibling manifest's skill
# is written).
# ---------------------------------------------------------------------------
init_fixture
write_slice "testing/core.md" "# core testing doctrine"
write_manifest "dev" "broken" "Has a slice that doesn't exist" \
  "skills/testing/core.md" "skills/testing/missing.md"
write_manifest "dev" "fine" "Would be valid on its own" \
  "skills/testing/core.md"

run_gen
assert_eq "missing slice: exit nonzero" "1" "$CODE"
assert_contains "missing slice: names the manifest" "$OUT" "dev/broken.md"
assert_contains "missing slice: names the missing path" "$OUT" "skills/testing/missing.md"
[[ -e "$SKILLS_DIR/persona-dev-broken" ]] && bad "missing slice: no dir for broken manifest" || ok "missing slice: no dir for broken manifest"
[[ -e "$SKILLS_DIR/persona-dev-fine" ]] && bad "missing slice: sibling manifest also not written (all-or-nothing)" || ok "missing slice: sibling manifest also not written (all-or-nothing)"

# ---------------------------------------------------------------------------
# Test 3: idempotence — a second run makes no changes; --check exits 0
# ---------------------------------------------------------------------------
init_fixture
write_slice "testing/core.md" "# core testing doctrine"
write_manifest "dev" "backend" "Backend engineer doctrine slice" "skills/testing/core.md"
run_gen
assert_eq "idempotence: first run exit 0" "0" "$CODE"

run_gen
assert_eq "idempotence: second run exit 0" "0" "$CODE"
assert_eq "idempotence: second run reports up to date" "up to date" "$OUT"

run_gen --check
assert_eq "idempotence: --check exit 0" "0" "$CODE"
assert_eq "idempotence: --check reports up to date" "up to date" "$OUT"

# ---------------------------------------------------------------------------
# Test 4: a modified manifest makes --check exit 1
# ---------------------------------------------------------------------------
init_fixture
write_slice "testing/core.md" "# core testing doctrine"
write_manifest "dev" "backend" "Backend engineer doctrine slice" "skills/testing/core.md"
run_gen
assert_eq "modified manifest: initial gen exit 0" "0" "$CODE"

write_manifest "dev" "backend" "Backend engineer doctrine slice, revised" "skills/testing/core.md"
run_gen --check
assert_eq "modified manifest: --check exit 1" "1" "$CODE"
assert_contains "modified manifest: --check reports the update" "$OUT" "would update: persona-dev-backend"

# ---------------------------------------------------------------------------
# Test 5: stale AUTO-GENERATED skill removed; hand-made persona-fake skill
# (no marker) preserved untouched.
# ---------------------------------------------------------------------------
init_fixture
write_slice "testing/core.md" "# core testing doctrine"
write_manifest "dev" "backend" "Backend engineer doctrine slice" "skills/testing/core.md"
write_manifest "dev" "stale" "About to lose its manifest" "skills/testing/core.md"
run_gen
assert_eq "stale cleanup: initial gen (2 manifests) exit 0" "0" "$CODE"
[[ -f "$SKILLS_DIR/persona-dev-stale/SKILL.md" ]] && ok "stale cleanup: stale skill exists before manifest removal" || bad "stale cleanup: stale skill exists before manifest removal"

mkdir -p "$SKILLS_DIR/persona-fake"
cat > "$SKILLS_DIR/persona-fake/SKILL.md" <<'EOF'
---
name: persona-fake
description: Hand-written skill that happens to match the persona-* naming pattern.
---
# Not auto-generated — must never be touched.
EOF
hand_made_before="$(cat "$SKILLS_DIR/persona-fake/SKILL.md")"

rm -f "$PERSONAS_DIR/dev/stale.md"
run_gen
assert_eq "stale cleanup: gen after removing stale manifest exit 0" "0" "$CODE"
assert_contains "stale cleanup: reports deletion" "$OUT" "deleted (stale): persona-dev-stale"
[[ -d "$SKILLS_DIR/persona-dev-stale" ]] && bad "stale cleanup: stale skill dir actually removed" || ok "stale cleanup: stale skill dir actually removed"
[[ -d "$SKILLS_DIR/persona-dev-backend" ]] && ok "stale cleanup: still-valid skill dir untouched" || bad "stale cleanup: still-valid skill dir untouched"
[[ -f "$SKILLS_DIR/persona-fake/SKILL.md" ]] && ok "stale cleanup: hand-made persona-fake preserved" || bad "stale cleanup: hand-made persona-fake preserved"
hand_made_after="$(cat "$SKILLS_DIR/persona-fake/SKILL.md")"
assert_eq "stale cleanup: hand-made persona-fake content unchanged" "$hand_made_before" "$hand_made_after"

# --check must also report the hand-made skill as untouched (no delete line
# for it) even though it shares the persona-* prefix.
run_gen --check
assert_not_contains "stale cleanup: --check never lists persona-fake" "$OUT" "persona-fake"

# ---------------------------------------------------------------------------
# Test 6: no manifests at all -> exit 0, graceful no-op
# ---------------------------------------------------------------------------
init_fixture
run_gen
assert_eq "no manifests: exit 0 (no personas dir)" "0" "$CODE"

init_fixture
mkdir -p "$PERSONAS_DIR"
run_gen
assert_eq "no manifests: exit 0 (empty personas dir)" "0" "$CODE"

# ---------------------------------------------------------------------------
# Bonus: --help and unknown-argument handling (bash -n / usage contract).
# ---------------------------------------------------------------------------
init_fixture
run_gen --help
assert_eq "help: exit 0" "0" "$CODE"
assert_contains "help: shows usage" "$OUT" "Usage:"

run_gen --bogus-flag
assert_eq "unknown arg: exit 2" "2" "$CODE"

# ---------------------------------------------------------------------------
# Bonus: kebab-case violation is caught.
# ---------------------------------------------------------------------------
init_fixture
write_slice "testing/core.md" "# core testing doctrine"
write_manifest "Dev_Team" "backend" "Not kebab-case group" "skills/testing/core.md"
run_gen
assert_eq "kebab-case: bad group exit nonzero" "1" "$CODE"
assert_contains "kebab-case: names the problem" "$OUT" "not kebab-case"

# ---------------------------------------------------------------------------
# Test 7: --local happy path — mixed plain + shared: slices, exact content.
# ---------------------------------------------------------------------------
init_fixture
write_slice "testing/core.md" "# core testing doctrine (shared)"
write_local_slice "personal/private-note.md" "# private-only doctrine"
write_local_manifest "dev" "solo" "Solo dev with a private slice plus a shared one" \
  "skills/personal/private-note.md" "shared:skills/testing/core.md"

run_gen_local
assert_eq "local happy path: exit 0" "0" "$CODE"
assert_contains "local happy path: reports created" "$OUT" "created: persona-dev-solo"

actual_local1="$(cat "$OUT_DIR/persona-dev-solo/SKILL.md")"
expected_local1="$(expected_local_skill_content "dev" "solo" "Solo dev with a private slice plus a shared one" \
  "skills/personal/private-note.md" "shared:skills/testing/core.md")"
assert_eq "local happy path: content exact" "$expected_local1" "$actual_local1"
assert_contains "local happy path: marked local-generated" "$actual_local1" "AUTO-GENERATED (local)"

# ---------------------------------------------------------------------------
# Test 8: --local missing --out / --shared-root -> exit 2, names the flag.
# ---------------------------------------------------------------------------
init_fixture
write_local_slice "testing/core.md" "# local core"
write_local_manifest "dev" "backend" "desc" "skills/testing/core.md"

OUT="$(GEN_PERSONA_ROOT="$TMP_ROOT" "$GEN_SRC" --local "$LOCAL_DIR" --shared-root "$CONTEXT_DIR" 2>&1)"
CODE=$?
assert_eq "local missing --out: exit 2" "2" "$CODE"
assert_contains "local missing --out: names the flag" "$OUT" "--out"

OUT="$(GEN_PERSONA_ROOT="$TMP_ROOT" "$GEN_SRC" --local "$LOCAL_DIR" --out "$OUT_DIR" 2>&1)"
CODE=$?
assert_eq "local missing --shared-root: exit 2" "2" "$CODE"
assert_contains "local missing --shared-root: names the flag" "$OUT" "--shared-root"

# ---------------------------------------------------------------------------
# Test 9: --local plain slice missing -> error; shared: slice missing in the
# shared root -> error naming the shared root.
# ---------------------------------------------------------------------------
init_fixture
write_local_manifest "dev" "brokenlocal" "Plain local slice that doesn't exist" \
  "skills/testing/missing.md"
run_gen_local
assert_eq "local plain slice missing: exit nonzero" "1" "$CODE"
assert_contains "local plain slice missing: names the path" "$OUT" "skills/testing/missing.md"

init_fixture
write_local_manifest "dev" "brokenshared" "References a shared slice that doesn't exist" \
  "shared:skills/testing/missing.md"
run_gen_local
assert_eq "shared slice missing: exit nonzero" "1" "$CODE"
assert_contains "shared slice missing: names the path" "$OUT" "skills/testing/missing.md"
assert_contains "shared slice missing: names the shared root" "$OUT" "shared root"

# ---------------------------------------------------------------------------
# Test 10: --local collision — an existing non-local-marked skill at the
# target name is never overwritten (error, not silent overwrite).
# ---------------------------------------------------------------------------
init_fixture
mkdir -p "$OUT_DIR/persona-dev-backend"
cat > "$OUT_DIR/persona-dev-backend/SKILL.md" <<'SKILLEOF'
---
name: persona-dev-backend
description: Persona loader — dev/backend: shared version (AUTO-GENERATED by tools/gen-persona-skills.sh — edit the manifest/slices and regenerate; do not hand-edit)
---
# Persona: dev/backend (live from ~/.claude/context/, local overlay wins)

!`for f in skills/testing/core.md; do if [ -f "$HOME/.claude/context-local/$f" ]; then cat "$HOME/.claude/context-local/$f"; else cat "$HOME/.claude/context/$f"; fi; done`
SKILLEOF
shared_before="$(cat "$OUT_DIR/persona-dev-backend/SKILL.md")"

write_local_slice "testing/core.md" "# local core override"
write_local_manifest "dev" "backend" "Local variant colliding with a shared-generated name" \
  "skills/testing/core.md"

run_gen_local
assert_eq "collision with shared: exit nonzero" "1" "$CODE"
assert_contains "collision with shared: names the colliding skill" "$OUT" "persona-dev-backend"
shared_after="$(cat "$OUT_DIR/persona-dev-backend/SKILL.md")"
assert_eq "collision with shared: shared skill left untouched" "$shared_before" "$shared_after"

# ---------------------------------------------------------------------------
# Test 11: --local stale cleanup only ever considers local-marked skills — a
# shared-generated persona-* skill sharing the --out dir is never deleted
# even when no local manifest names it (marker distinguishes the two modes).
# ---------------------------------------------------------------------------
init_fixture
mkdir -p "$OUT_DIR/persona-shared-only"
cat > "$OUT_DIR/persona-shared-only/SKILL.md" <<'SKILLEOF'
---
name: persona-shared-only
description: Persona loader — shared/only: only exists via the shared repo (AUTO-GENERATED by tools/gen-persona-skills.sh — edit the manifest/slices and regenerate; do not hand-edit)
---
# Persona: shared/only (live from ~/.claude/context/, local overlay wins)

!`for f in skills/testing/core.md; do if [ -f "$HOME/.claude/context-local/$f" ]; then cat "$HOME/.claude/context-local/$f"; else cat "$HOME/.claude/context/$f"; fi; done`
SKILLEOF

write_local_slice "testing/core.md" "# local core"
write_local_manifest "dev" "backend" "Stays around after the sibling manifest is removed" "skills/testing/core.md"
write_local_manifest "dev" "temp" "Will lose its manifest next" "skills/testing/core.md"
run_gen_local
assert_eq "local stale: initial gen exit 0" "0" "$CODE"
[[ -f "$OUT_DIR/persona-dev-temp/SKILL.md" ]] && ok "local stale: local skill created" || bad "local stale: local skill created"

rm -f "$LOCAL_DIR/personas/dev/temp.md"
run_gen_local
assert_eq "local stale: gen after removing manifest exit 0" "0" "$CODE"
assert_contains "local stale: reports deletion of local-marked skill" "$OUT" "deleted (stale): persona-dev-temp"
[[ -d "$OUT_DIR/persona-dev-temp" ]] && bad "local stale: local skill actually removed" || ok "local stale: local skill actually removed"
[[ -d "$OUT_DIR/persona-dev-backend" ]] && ok "local stale: still-valid local skill dir untouched" || bad "local stale: still-valid local skill dir untouched"
[[ -d "$OUT_DIR/persona-shared-only" ]] && ok "local stale: unrelated shared-marked skill never touched" || bad "local stale: unrelated shared-marked skill never touched"

# ---------------------------------------------------------------------------
# Test 12: --local --check works (up to date / would update).
# ---------------------------------------------------------------------------
init_fixture
write_local_slice "testing/core.md" "# local core"
write_local_manifest "dev" "backend" "desc" "skills/testing/core.md"
run_gen_local
assert_eq "local --check: initial gen exit 0" "0" "$CODE"

run_gen_local --check
assert_eq "local --check: up to date exit 0" "0" "$CODE"
assert_eq "local --check: reports up to date" "up to date" "$OUT"

write_local_manifest "dev" "backend" "desc revised" "skills/testing/core.md"
run_gen_local --check
assert_eq "local --check: modified manifest exit 1" "1" "$CODE"
assert_contains "local --check: reports would update" "$OUT" "would update: persona-dev-backend"

# ---------------------------------------------------------------------------
# Summary
# ---------------------------------------------------------------------------
echo
echo "----------------------------------------"
echo "pass=$pass fail=$fail"
if [[ "$fail" -eq 0 ]]; then
  echo "ALL TESTS PASSED"
  exit 0
else
  echo "TESTS FAILED"
  exit 1
fi
